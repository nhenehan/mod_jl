# Generates every artefact derived from schema/jlp2.xsd, so enum ordinals and the
# schema hash are never written by hand:
#
#   libjlproto/src/gen/jlp_vocab.h, jlp_vocab.c   C name tables and lookups
#   jl_serv/JlServ/src/gen/vocab.jl               Julia name tables and the hash
#   jl_serv/JlServ/src/gen/jlp_tables.jl          JExi static grammar tables
#
# Usage: julia --project=jl_serv/JlServ tools/gen.jl [--check]
# With --check nothing is written; the exit status is 1 if any file is stale.

using JExi
using SHA

const ROOT = dirname(@__DIR__)
const XSD = joinpath(ROOT, "schema", "jlp2.xsd")
const C_DIR = joinpath(ROOT, "libjlproto", "src", "gen")
const JL_DIR = joinpath(ROOT, "jl_serv", "JlServ", "src", "gen")
const BANNER = "generated by tools/gen.jl from schema/jlp2.xsd. Do not edit by hand."

"""The enumeration values of the named simpleType, in schema order."""
function enum_values(xsd::String, type_name::String)
    m = match(Regex("<xs:simpleType name=\"$type_name\">(.*?)</xs:simpleType>", "s"), xsd)
    m === nothing && error("simpleType $type_name not found in $XSD")
    return [x[1] for x in eachmatch(r"<xs:enumeration value=\"([^\"]+)\"/>", m[1])]
end

c_ident(s) = uppercase(replace(s, '-' => '_'))

function c_header(methods, headers, sha)
    io = IOBuffer()
    println(io, "/* ", BANNER, " */")
    println(io, "#ifndef JLP_VOCAB_H\n#define JLP_VOCAB_H\n\n#include <stddef.h>\n#include <stdint.h>\n")
    println(io, "#define JLP_METHOD_COUNT ", length(methods))
    println(io, "#define JLP_HEADER_COUNT ", length(headers), "\n")
    println(io, "enum jlp_method {")
    for (i, m) in enumerate(methods)
        println(io, "    JLP_M_", c_ident(m), " = ", i - 1, ",")
    end
    println(io, "};\n\nenum jlp_header {")
    for (i, h) in enumerate(headers)
        println(io, "    JLP_H_", c_ident(h), " = ", i - 1, ",")
    end
    println(io, "};\n")
    println(io, "/* SHA-256 of schema/jlp2.xsd as it was when this file was generated. */")
    println(io, "extern const uint8_t jlp_vocab_schema_sha256[32];\n")
    println(io, "extern const char *const jlp_method_names[JLP_METHOD_COUNT];")
    println(io, "extern const char *const jlp_header_names[JLP_HEADER_COUNT];")
    println(io, "extern const uint8_t jlp_header_name_lens[JLP_HEADER_COUNT];\n")
    println(io, "/* Ordinal of an exact (case-sensitive) method name, or -1. */")
    println(io, "int jlp_method_lookup(const char *name, size_t len);")
    println(io, "/* Ordinal of a header name compared case-insensitively, or -1. */")
    println(io, "int jlp_header_lookup(const char *name, size_t len);\n")
    println(io, "#endif")
    return String(take!(io))
end

# Lookups switch on the length first, so at most a handful of compares run.
function c_lookup(io, fname, names, casefold)
    cmp = casefold ? "jlp_ieq" : "memcmp_eq"
    println(io, "int ", fname, "(const char *name, size_t len)\n{")
    println(io, "    switch (len) {")
    bylen = Dict{Int,Vector{Int}}()
    for (i, n) in enumerate(names)
        push!(get!(bylen, ncodeunits(n), Int[]), i - 1)
    end
    for len in sort!(collect(keys(bylen)))
        println(io, "    case ", len, ":")
        for o in bylen[len]
            println(io, "        if (", cmp, "(name, \"", names[o+1], "\", ", len, ")) return ", o, ";")
        end
        println(io, "        return -1;")
    end
    println(io, "    default:\n        return -1;\n    }\n}\n")
end

function c_source(methods, headers, sha)
    io = IOBuffer()
    println(io, "/* ", BANNER, " */")
    println(io, "#include \"jlp_vocab.h\"\n\n#include <string.h>\n")
    println(io, "const uint8_t jlp_vocab_schema_sha256[32] = {")
    for row in Iterators.partition(sha, 8)
        println(io, "    ", join(("0x" * string(b; base = 16, pad = 2) for b in row), ", "), ",")
    end
    println(io, "};\n")
    println(io, "const char *const jlp_method_names[JLP_METHOD_COUNT] = {")
    foreach(m -> println(io, "    \"", m, "\","), methods)
    println(io, "};\n")
    println(io, "const char *const jlp_header_names[JLP_HEADER_COUNT] = {")
    foreach(h -> println(io, "    \"", h, "\","), headers)
    println(io, "};\n")
    println(io, "const uint8_t jlp_header_name_lens[JLP_HEADER_COUNT] = {")
    for row in Iterators.partition(headers, 16)
        println(io, "    ", join((string(ncodeunits(h)) for h in row), ", "), ",")
    end
    println(io, "};\n")
    println(io, "static int memcmp_eq(const char *a, const char *b, size_t n)\n{\n    return memcmp(a, b, n) == 0;\n}\n")
    # The known names are lowercase ASCII, so folding only the input is enough.
    println(io, "static int jlp_ieq(const char *a, const char *lower, size_t n)\n{")
    println(io, "    for (size_t i = 0; i < n; i++) {")
    println(io, "        unsigned char c = (unsigned char)a[i];")
    println(io, "        if (c >= 'A' && c <= 'Z')\n            c += 'a' - 'A';")
    println(io, "        if (c != (unsigned char)lower[i])\n            return 0;")
    println(io, "    }\n    return 1;\n}\n")
    c_lookup(io, "jlp_method_lookup", methods, false)
    c_lookup(io, "jlp_header_lookup", headers, true)
    return String(take!(io))
end

function jl_vocab(methods, headers, sha)
    io = IOBuffer()
    println(io, "# ", BANNER, "\n")
    println(io, "\"\"\"SHA-256 of schema/jlp2.xsd when this file was generated.\"\"\"")
    println(io, "const SCHEMA_SHA256 = hex2bytes(\"", bytes2hex(sha), "\")\n")
    println(io, "\"\"\"Method names by ordinal + 1.\"\"\"")
    println(io, "const METHOD_NAMES = String[", join(repr.(methods), ", "), "]\n")
    println(io, "\"\"\"Known header names (lowercase) by ordinal + 1.\"\"\"")
    println(io, "const HEADER_NAMES = String[")
    for row in Iterators.partition(headers, 6)
        println(io, "    ", join(repr.(row), ", "), ",")
    end
    println(io, "]")
    return String(take!(io))
end

function main(args)
    check = "--check" in args
    xsd = read(XSD, String)
    sha = sha256(read(XSD))
    methods = enum_values(xsd, "MethodName")
    headers = enum_values(xsd, "HeaderName")
    length(headers) <= 127 || error("HeaderName has $(length(headers)) values; keep it to 127 so the code is one byte")
    files = [
        joinpath(C_DIR, "jlp_vocab.h") => c_header(methods, headers, sha),
        joinpath(C_DIR, "jlp_vocab.c") => c_source(methods, headers, sha),
        joinpath(JL_DIR, "vocab.jl") => jl_vocab(methods, headers, sha),
    ]
    stale = String[]
    for (path, text) in files
        if check
            (isfile(path) && read(path, String) == text) || push!(stale, path)
        else
            mkpath(dirname(path))
            write(path, text)
        end
    end
    tables = joinpath(JL_DIR, "jlp_tables.jl")
    fresh = JExi.SchemaGen.generate([XSD]; out = tables, name = "TABLES", module_name = "JlpTables", check)
    fresh || push!(stale, tables)
    if check
        isempty(stale) && (println("vocab: up to date"); return 0)
        foreach(p -> println(stderr, "stale: ", relpath(p, ROOT)), stale)
        return 1
    end
    println("vocab: wrote ", length(files) + 1, " files (", length(methods), " methods, ", length(headers), " headers)")
    return 0
end

exit(main(ARGS))
